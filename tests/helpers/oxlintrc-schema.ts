import { type RuleName, rules } from "../../src/rules";
import { AREAS, LAYER_FOLDERS, type SpartaSettings, type TopFolder } from "../../src/utils/conventions";

type JsonSchema = Record<string, unknown>;

const TOP_FOLDERS: readonly TopFolder[] = ["sparta", "tests"];

/** A schema property with the same text for VS Code's plain and markdown hovers. */
const described = (text: string, schema: JsonSchema): JsonSchema => ({
	description: text.replaceAll("`", ""),
	markdownDescription: text,
	...schema,
});

const nonEmptyString = { type: "string", minLength: 1 };

const nameList = (text: string): JsonSchema =>
	described(text, { type: "array", items: nonEmptyString, uniqueItems: true });

const nameMapping = (text: string, targets: readonly string[], example: Record<string, string>): JsonSchema =>
	described(text, {
		type: "object",
		additionalProperties: { type: "string", enum: targets },
		defaultSnippets: [{ body: example }],
	});

/** One entry per setting: the `Record` makes `tsc` fail when a setting is added without a schema. */
const SETTINGS: Record<keyof Required<SpartaSettings>, JsonSchema> = {
	root: described(
		"Project root: aliases resolve against it, and only paths below it are matched. A relative path resolves against the folder the linter runs in. Default: the nearest folder with a `package.json`.",
		nonEmptyString
	),
	folders: described("Names of the two top-level folders. Replaces the defaults `sparta` and `tests`.", {
		type: "object",
		properties: { sparta: nonEmptyString, tests: nonEmptyString },
		additionalProperties: false,
	}),
	areas: nameMapping(
		'Extra area folders, each following a standard area, e.g. `{ "web": "ui" }`. Each area folder is still isolated from the others.',
		AREAS,
		{ web: "ui" }
	),
	layers: nameMapping(
		'Extra layer folders, each following a standard layer folder (its layer rules and file suffix), e.g. `{ "page-objects": "pages" }`.',
		Object.keys(LAYER_FOLDERS),
		{ "page-objects": "pages" }
	),
	aliases: nameMapping(
		'Extra path aliases pointing to the `sparta` or `tests` folder, e.g. `{ "@app/*": "sparta" }`. Only needed when they are not in your tsconfig `paths`.',
		TOP_FOLDERS,
		{ "@app/*": "sparta" }
	),
	supportModule: described(
		"The module `expect` must be imported from inside the sparta folder. Replaces the default `@sparta/support`.",
		nonEmptyString
	),
	pollingMethods: nameList("Extra retrying methods, added to `toPass`, `toPassAndReturn`, `poll` and `pollAndReturn`."),
	stepDecorators: nameList("Extra decorators that count as `@step`."),
	expectNames: nameList("Extra assertion functions that tests must not call, added to `expect` and `expectly…`."),
};

const ruleSchemas = (): JsonSchema =>
	Object.fromEntries(
		(Object.keys(rules) as RuleName[]).map(name => {
			const { docs } = rules[name].meta ?? {};

			return [
				`sparta/${name}`,
				{
					description: docs?.description,
					markdownDescription: `${docs?.description}\n\n[Documentation](${docs?.url})`,
					anyOf: [
						{ $ref: "#/definitions/spartaSeverity" },
						{ type: "array", items: [{ $ref: "#/definitions/spartaSeverity" }], minItems: 1, maxItems: 1 },
					],
				},
			];
		})
	);

/**
 * JSON schema for `.oxlintrc.json`: oxlint's own schema, plus the sparta rules and `settings.sparta`.
 * The `$ref` is relative to `node_modules/@cerios/sparta-lint-rules/`, so it follows the installed oxlint.
 */
export function oxlintrcSchema(): JsonSchema {
	const spartaRules = { properties: ruleSchemas() };

	return {
		$schema: "http://json-schema.org/draft-07/schema#",
		title: "Oxlintrc with @cerios/sparta-lint-rules",
		description:
			"oxlint's configuration schema, extended with the sparta rules and settings.sparta. Generated by tests/oxlintrc-schema.test.ts; do not edit.",
		allOf: [
			{ $ref: "../../oxlint/configuration_schema.json" },
			{
				properties: {
					rules: spartaRules,
					overrides: { items: { properties: { rules: spartaRules } } },
					settings: {
						properties: {
							sparta: described(
								"Describes a SPARTA project whose names differ from the standard ones. Settings never relax the rules. See https://github.com/CeriosTesting/sparta-lint-rules#configuration",
								{ type: "object", properties: SETTINGS, additionalProperties: false }
							),
						},
					},
				},
			},
		],
		definitions: {
			spartaSeverity: {
				description: "off/allow: off, warn: warning, error/deny: error. The sparta rules take no options.",
				enum: ["off", "warn", "error", "allow", "deny", 0, 1, 2],
			},
		},
	};
}
